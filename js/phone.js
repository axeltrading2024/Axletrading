/**
 * WhatsApp 号码校验（全站共用）
 *
 * 两个地方会用到，规则必须完全一致，所以抽出来：
 *   1) 购物车抽屉（js/app.js）—— 留号前移到抽屉，客户填完就落库
 *   2) 付款页（pay.html）—— 最后一道留号入口
 *
 * 规则：
 *   · 必须带国家码（+ 开头）
 *   · E.164 位数：8~15 位数字
 *   · 国家码首位不能是 0
 *   · 拒绝全相同数字（+0000000000）、纯递增/纯递减（+123456789）
 *   · 按国家码校验号段（如 +86 必须是 1[3-9] 开头 11 位）
 *     —— 收 60+ 个主要贸易市场；未收录的国家码走宽松规则，避免误伤小国客户
 *
 * 用法：
 *   EDDPhone.normalize('+34 612 345 678')  // → '+34612345678'
 *   EDDPhone.normalize('+86 265816816')    // → ''（号段不符）
 *   EDDPhone.valid('+34 612 345 678')      // → true
 */
(function (global) {
  'use strict';

  var CC_RULES = {
    '1': /^[2-9]\d{9}$/, '7': /^[349]\d{9}$/, '20': /^1[0-2]\d{8}$/, '27': /^[1-8]\d{8}$/,
    '30': /^6\d{9}$/, '31': /^6\d{8}$/, '32': /^4\d{8}$/, '33': /^[67]\d{8}$/,
    '34': /^[679]\d{8}$/, '36': /^[237]\d{8}$/, '39': /^3\d{8,9}$/, '40': /^7\d{8}$/,
    '41': /^7\d{8}$/, '43': /^6\d{8,10}$/, '44': /^7\d{9}$/, '45': /^[2-9]\d{7}$/,
    '46': /^7\d{8}$/, '47': /^[49]\d{7}$/, '48': /^[5-8]\d{8}$/, '49': /^1[5-7]\d{8,9}$/,
    '212': /^6\d{8}$/, '234': /^[789]\d{9}$/, '254': /^[17]\d{8}$/,
    '351': /^[29]\d{8}$/, '352': /^6\d{8}$/, '353': /^8\d{8}$/, '358': /^4\d{7,9}$/,
    '370': /^6\d{7}$/, '371': /^2\d{7}$/, '372': /^[3-5]\d{6,7}$/, '380': /^[679]\d{8}$/,
    '385': /^9\d{8}$/, '386': /^[3-7]\d{7}$/, '420': /^[67]\d{8}$/, '421': /^9\d{8}$/,
    '51': /^9\d{8}$/, '52': /^[1-9]\d{9}$/, '55': /^[1-9]{2}9\d{8}$/, '56': /^9\d{8}$/, '57': /^3\d{9}$/,
    '60': /^1\d{8,9}$/, '61': /^4\d{8}$/, '62': /^8\d{8,11}$/, '63': /^9\d{9}$/,
    '64': /^2\d{7,9}$/, '65': /^[89]\d{7}$/, '66': /^[689]\d{8}$/,
    '81': /^[789]0\d{8}$/, '82': /^1\d{8,9}$/, '84': /^[35789]\d{8}$/, '86': /^1[3-9]\d{9}$/,
    '90': /^5\d{9}$/, '91': /^[6-9]\d{9}$/, '92': /^3\d{9}$/, '94': /^7\d{8}$/,
    '880': /^1\d{9}$/, '965': /^[569]\d{7}$/, '966': /^5\d{8}$/, '968': /^[79]\d{7}$/,
    '971': /^5\d{8}$/, '972': /^5\d{8}$/, '973': /^3\d{7}$/, '974': /^[3-7]\d{7}$/
  };

  /* 返回 true=通过 / false=国家码已收录但号段不符 / null=国家码未收录 */
  function checkNational(d) {
    var hit = false;
    for (var len = 3; len >= 1; len--) {
      if (d.length <= len + 5) continue;
      var cc = d.slice(0, len);
      if (!Object.prototype.hasOwnProperty.call(CC_RULES, cc)) continue;
      hit = true;
      if (CC_RULES[cc].test(d.slice(len))) return true;
    }
    return hit ? false : null;
  }

  function sequential(d) {
    var up = true, down = true;
    for (var i = 1; i < d.length; i++) {
      var df = (+d.charAt(i)) - (+d.charAt(i - 1));
      if (df !== 1) up = false;
      if (df !== -1) down = false;
    }
    return up || down;
  }

  function normalize(v) {
    var s = String(v || '').trim();
    if (s.charAt(0) !== '+') return '';             // 必须带国家码
    var d = s.slice(1).replace(/\D/g, '');           // 只留数字
    if (d.length < 8 || d.length > 15) return '';    // E.164 位数
    if (d.charAt(0) === '0') return '';              // 国家码首位不能是 0
    if (/^(\d)\1+$/.test(d)) return '';              // 全相同
    if (sequential(d)) return '';                    // 纯顺序
    if (checkNational(d) === false) return '';       // 国家码对、号段错
    return '+' + d;
  }

  global.EDDPhone = {
    normalize: normalize,
    valid: function (v) { return !!normalize(v); },
    /* 给后台/跳转用：去掉 + 与分隔符的纯数字 */
    digits: function (v) { return String(v || '').replace(/\D/g, ''); }
  };
})(typeof window !== 'undefined' ? window : this);
